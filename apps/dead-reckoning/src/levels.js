export const LEVEL_ROWS = 16;

export function parseLevel({ id, name, rows }) {
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  const solid = new Uint8Array(w * h);
  const visible = new Uint8Array(w * h);
  const hazard = new Uint8Array(w * h);
  let spawn = null;
  let goal = null;
  rows.forEach((row, i) => {
    const r = h - 1 - i;
    for (let c = 0; c < w; c++) {
      const ch = row[c] ?? '.';
      const k = r * w + c;
      if (ch === '#' || ch === '=') solid[k] = 1;
      if (ch === '=') visible[k] = 1;
      if (HAZARD_KIND[ch]) hazard[k] = HAZARD_KIND[ch];
      if (ch === 'S') spawn = { x: c + 0.5, y: r };
      if (ch === 'G') goal = { x: c + 0.5, y: r };
    }
  });
  if (!spawn || !goal) throw new Error(`level ${id} needs an S and a G`);
  return { id, name, w, h, solid, visible, hazard, spawn, goal, rows };
}

export const LEVELS = RAW.map(parseLevel);

/** The world box a level's markers and maps cover (the abyss included). */
export function levelBounds(lv) {
  return { min: [0, -1.5], max: [lv.w, lv.h] };
}
